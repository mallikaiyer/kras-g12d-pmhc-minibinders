#!/usr/bin/env python
"""Stage 01 - the structural survey underpinning the design plan.

Regenerates every structural number quoted in docs/design_plan.md:

  * which peptide copies have modelled coordinates at the central positions
  * backbone phi/psi across the central peptide residues
  * the orientation of position 6 relative to the HLA groove, per copy
  * distances from the Asp6 carboxylate to the TCR and HLA residues of interest

Outputs TSV tables plus a human-readable SUMMARY.md under results/survey/.

Usage:
    python scripts/01_structure_survey.py
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from kras_pmhc import structures, survey  # noqa: E402
from kras_pmhc.constants import MUTANT_POSITION, STRUCTURES  # noqa: E402

OUT_DIR = REPO_ROOT / "results" / "survey"


def write_tsv(path: Path, rows: list[dict]) -> None:
    """Write rows to TSV, unioning keys so optional columns are not dropped."""
    if not rows:
        return
    fieldnames: list[str] = []
    for row in rows:
        for key in row:
            if key not in fieldnames:
                fieldnames.append(key)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames, delimiter="\t")
        writer.writeheader()
        for row in rows:
            writer.writerow({k: "" if row.get(k) is None else row.get(k) for k in fieldnames})


def summarise(density: list[dict], orientation: list[dict], contacts: list[dict]) -> str:
    """Build the markdown summary, highlighting the decision-relevant findings."""
    lines = [
        "# Structural survey",
        "",
        "Generated by `scripts/01_structure_survey.py`. Do not edit by hand.",
        "",
        "## Completeness at the central peptide positions",
        "",
        "Position 6 is the only residue that differs between the two assay targets.",
        "",
        "| PDB | peptide chain | residues 5-7 modelled | sequence observed |",
        "|---|---|---|---|",
    ]

    by_chain: dict[tuple[str, str], list[dict]] = {}
    for row in density:
        by_chain.setdefault((row["pdb_id"], row["peptide_chain"]), []).append(row)
    for (pdb_id, chain), rows in sorted(by_chain.items()):
        central = [r for r in rows if r["res_id"] in (5, 6, 7)]
        modelled = sum(1 for r in central if r["observed"])
        seq = "".join(
            (r["res_name"][:1] if r["observed"] else "-")
            for r in sorted(rows, key=lambda r: r["res_id"])
        )
        lines.append(f"| {pdb_id} | {chain} | {modelled}/3 | `{seq}` |")

    lines += [
        "",
        "Note the sequence column uses the first letter of the three-letter code,",
        "so it is a completeness map rather than a true one-letter sequence.",
        "",
        "## Orientation of position 6",
        "",
        "Distance to the tip of HLA Arg114, the partner the Asp carboxylate pairs",
        "with when buried. `cb_minus_ca` greater than zero means the side chain",
        "leans away from the groove.",
        "",
        "| PDB | chain | residue | TCR | Ca->ref | Cb->ref | Cb-Ca | points | side-chain SASA |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in orientation:
        if row.get("note"):
            lines.append(
                f"| {row['pdb_id']} | {row['peptide_chain']} | - | - | - | - | - | "
                f"{row['note']} | - |"
            )
            continue
        sasa = row["sidechain_sasa_pmhc_only"]
        lines.append(
            f"| {row['pdb_id']} | {row['peptide_chain']} | {row['res_name']}6 "
            f"| {'yes' if row['tcr_present'] else 'no'} "
            f"| {row['ca_to_ref']} | {row['cb_to_ref']} ({row['cb_source'][:4]}) "
            f"| {row['cb_minus_ca']:+.2f} | {row['points']} "
            f"| {'n/a (Gly)' if sasa is None else sasa} |"
        )

    lines += [
        "",
        "## Distance from the Asp6 carboxylate to the discriminating residues",
        "",
        "TCR per-residue binding-energy differences are from Poole et al. Fig. 3b-d.",
        "The two largest contributors are the most distant, which is the evidence",
        "that the TCR's specificity is not contact-mediated.",
        "",
        "| PDB | partner | role | ddG (kcal/mol) | to carboxylate | to any Asp6 atom |",
        "|---|---|---|---|---|---|",
    ]
    for row in contacts:
        if row.get("note") == "not modelled":
            continue
        ddg = row["ddG_kcal_per_mol"]
        lines.append(
            f"| {row['pdb_id']} | {row['partner']} | {row['role']} "
            f"| {'' if ddg is None else ddg} "
            f"| {row.get('to_carboxylate', '')} | {row.get('to_any_asp6_atom', '')} |"
        )

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    density: list[dict] = []
    dihedrals: list[dict] = []
    orientation: list[dict] = []
    contacts: list[dict] = []

    for pdb_id in sorted(STRUCTURES):
        array = structures.load(pdb_id)

        # Fails loudly if we are reading the wrong chain or the wrong entry.
        observed = structures.check_peptide_identity(array, pdb_id)
        pairs = structures.pair_peptides_with_heavy_chains(array)
        print(f"{pdb_id}: {len(observed)} peptide copy/copies, pairing {pairs}")
        for chain, seq in sorted(observed.items()):
            print(f"    chain {chain}: {seq}")

        density += survey.peptide_density(array, pdb_id)
        dihedrals += survey.peptide_dihedrals(array, pdb_id)
        orientation += survey.position6_orientation(array, pdb_id)

        # Contacts need a modelled Asp6. TCR partners are only defined for
        # 7OW6; other entries contribute their HLA contacts alone.
        if STRUCTURES[pdb_id].peptide[MUTANT_POSITION - 1] == "D" and all(
            STRUCTURES[pdb_id].peptide[MUTANT_POSITION - 1] == seq[MUTANT_POSITION - 1]
            for seq in observed.values()
        ):
            contacts += survey.mutant_contacts(array, pdb_id)

    write_tsv(args.out_dir / "peptide_density.tsv", density)
    write_tsv(args.out_dir / "peptide_dihedrals.tsv", dihedrals)
    write_tsv(args.out_dir / "position6_orientation.tsv", orientation)
    write_tsv(args.out_dir / "mutant_contacts.tsv", contacts)
    (args.out_dir / "SUMMARY.md").write_text(summarise(density, orientation, contacts))

    print(f"\nwrote 4 tables and SUMMARY.md to {args.out_dir.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
